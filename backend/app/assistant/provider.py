class AssistantProvider(Protocol):
    name: str

    def explain_decision(self, d: AccessDecision) -> dict[str, Any]: ...
    def summarize_incident(self, i: Incident) -> dict[str, Any]: ...
    def explain_audit(self, a: AuditLog) -> dict[str, Any]: ...
    def interpret_risk(self, u: User, score: int, factors: list[dict]) -> dict[str, Any]: ...
    def review_activity(self, db: Session, hours: int) -> dict[str, Any]: ...
    def ask(self, db: Session, question: str, user: User) -> dict[str, Any]: ...


def _resp(title: str, summary: str, findings: list[str], recommendations: list[str], **extra) -> dict[str, Any]:
    return {"title": title, "summary": summary, "findings": findings, "recommendations": recommendations,
            "advisory": True, "provider": "local-rules", "disclaimer": DISCLAIMER, **extra}


class LocalRuleAssistant:
    name = "local-rules"

    def explain_decision(self, d: AccessDecision) -> dict[str, Any]:
        ctx = d.context or {}
        failed = [t for t in d.trace if t.get("result") == "fail"]
        matched = [t for t in d.trace if t.get("result") == "match"]
        findings = [f"{t['check']}: {t['detail']}" for t in failed]
        findings += [f"Policy matched - {t['check']} ({t['detail']})" for t in matched]
        recs = []
        dev = (ctx.get("device") or {}).get("trust_status")
        if d.decision == "REQUIRE_MFA":
            recs.append("Complete step-up MFA from the access prompt, or enrol in MFA under Settings > Security.")
        if d.decision == "REQUIRE_DEVICE_VERIFICATION" or dev in ("pending_verification", "untrusted"):
            recs.append("Ask a Security Administrator to verify the device in Device Trust.")
        if any("entitled" in t["check"].lower() for t in failed):
            recs.append("Submit an access request with a business justification.")
        if any("risk" in t["check"].lower() for t in failed):
            recs.append("Investigate open alerts for this user; risk must fall below the block threshold.")
        if not recs and d.decision == "DENY":
            recs.append("Review the deciding policy in the Policy Engine and confirm it reflects intent.")
        res = (ctx.get("resource") or {}).get("name", "the resource")
        summary = (f"The engine returned {d.decision} for {(ctx.get('user') or {}).get('email', 'the user')} on {res}: "
                   f"{ACTION_MEANING.get(d.decision, '')}. Primary reason: {d.reasons[0] if d.reasons else 'n/a'}.")
        return _resp("Access decision explained", summary, findings or ["All baseline checks passed."], recs)

    def summarize_incident(self, i: Incident) -> dict[str, Any]:
        users = sorted({a.user.email for a in i.alerts if a.user})
        cats = sorted({a.category for a in i.alerts})
        hours = (utcnow() - i.created_at).total_seconds() / 3600
        findings = [f"Severity {i.severity}, status {i.status}, open for {hours:.1f} hours.",
                    f"{len(i.alerts)} linked alert(s){': ' + ', '.join(cats) if cats else ''}.",
                    f"Affected users: {', '.join(users) if users else 'none linked'}.",
                    f"{len([n for n in i.notes if n.note_type == 'note'])} investigation note(s); assignee: "
                    f"{i.assignee.full_name if i.assignee else 'unassigned'}."]
        recs = []
        if not i.assignee:
            recs.append("Assign an investigator.")
        if i.severity in ("critical", "high") and i.status == "open":
            recs.append("Begin investigation promptly; consider containing affected sessions and devices.")
        for a in i.alerts[:3]:
            recs.append(a.recommended_action)
        if i.status == "contained":
            recs.append("Document root cause and write a resolution summary before resolving.")
        last = next((n.body for n in reversed(i.notes) if n.note_type == "note"), None)
        summary = f"{i.reference} '{i.title}'. " + (f"Latest note: \"{last[:160]}\"" if last else "No analyst notes yet.")
        return _resp(f"Incident summary - {i.reference}", summary, findings, list(dict.fromkeys(recs)))

    def explain_audit(self, a: AuditLog) -> dict[str, Any]:
        base = AUDIT_EXPLAIN.get(a.action, f"Recorded '{a.action}' in category '{a.category}'.")
        findings = [f"Actor: {a.actor_email or 'system'}", f"Outcome: {a.outcome}, severity: {a.severity}"]
        if a.target_label or a.target_id:
            findings.append(f"Target: {a.target_type} {a.target_label or a.target_id}")
        if a.ip_address:
            findings.append(f"Source IP: {a.ip_address}")
        for k, v in list((a.details or {}).items())[:6]:
            findings.append(f"{k}: {v}")
        recs = []
        if a.outcome == "failure" and a.category == "authentication":
            recs.append("Check the user's recent login history for repeated failures.")
        if a.severity in ("high", "critical"):
            recs.append("Correlate with open threat alerts and consider opening an incident.")
        if a.is_demo:
            recs.append("This is seeded demonstration data, not a runtime event.")
        return _resp("Audit event explained", base, findings, recs)

    def interpret_risk(self, u: User, score: int, factors: list[dict]) -> dict[str, Any]:
        lvl = risk.level(score)
        findings = [f"{f['label']} (+{f['points']})" for f in sorted(factors, key=lambda f: -f["points"])]
        recs = []
        keys = {f["factor"] for f in factors}
        if "no_mfa" in keys:
            recs.append("Require the user to enrol in MFA.")
        if "untrusted_device" in keys:
            recs.append("Verify or block the user's unverified device.")
        if "failed_login" in keys:
            recs.append("Confirm recent failed logins were the user; reset the password if not.")
        if "open_alert_high" in keys:
            recs.append("Triage the user's open high-severity alerts.")
        summary = (f"{u.full_name} has a risk score of {score}/100 ({lvl}). The score is the sum of explainable "
                   f"factors over the last 24 hours, capped at 100.")
        return _resp("Risk score interpretation", summary, findings or ["No contributing risk factors."], recs,
                     score=score, level=lvl)

    def review_activity(self, db: Session, hours: int) -> dict[str, Any]:
        since = utcnow() - timedelta(hours=hours)
        c = lambda q: db.scalar(q) or 0  # noqa: E731
        logins = c(select(func.count()).select_from(SecurityEvent).where(SecurityEvent.event_type == "login_success", SecurityEvent.created_at >= since))
        fails = c(select(func.count()).select_from(SecurityEvent).where(SecurityEvent.event_type == "login_failure", SecurityEvent.created_at >= since))
        denies = c(select(func.count()).select_from(AccessDecision).where(AccessDecision.decision == "DENY", AccessDecision.evaluated_at >= since))
        evals = c(select(func.count()).select_from(AccessDecision).where(AccessDecision.evaluated_at >= since))
        alerts = db.execute(select(ThreatAlert.severity, func.count()).where(ThreatAlert.detected_at >= since).group_by(ThreatAlert.severity)).all()
        top_fail = db.execute(select(SecurityEvent.email_attempted, func.count()).where(
            SecurityEvent.event_type == "login_failure", SecurityEvent.created_at >= since)
            .group_by(SecurityEvent.email_attempted).order_by(func.count().desc()).limit(3)).all()
        findings = [f"{logins} successful and {fails} failed sign-ins.",
                    f"{evals} access evaluations, {denies} denied ({round(100 * denies / evals) if evals else 0}%).",
                    "Alerts: " + (", ".join(f"{n} {s}" for s, n in alerts) if alerts else "none")]
        if top_fail:
            findings.append("Most failed sign-ins: " + ", ".join(f"{e} ({n})" for e, n in top_fail))
        recs = []
        if fails > logins and fails > 5:
            recs.append("Failed sign-ins exceed successes - check for credential attacks.")
        if evals and denies / evals > 0.3:
            recs.append("High denial ratio - review recent policy changes or missing entitlements.")
        if any(s in ("critical", "high") for s, _ in alerts):
            recs.append("Triage high/critical alerts in Threat Detection.")
        return _resp(f"Activity review - last {hours}h", f"Summary of security activity over the last {hours} hours.",
                     findings, recs or ["No significant anomalies detected by the rule set."])

    def ask(self, db: Session, question: str, user: User) -> dict[str, Any]:
        ql = question.lower()
        if any(w in ql for w in ("risk", "risky", "score")):
            top = db.execute(select(User).where(User.status == "active").order_by(User.risk_score.desc()).limit(5)).scalars().all()
            return _resp("Highest-risk users", "Users ranked by current risk score.",
                         [f"{u.full_name} ({u.email}) - {u.risk_score} {risk.level(u.risk_score)}" for u in top],
                         ["Open a user in Identity Management and use 'Interpret risk' for a factor breakdown."])
        if any(w in ql for w in ("incident", "investigation")):
            rows = db.execute(select(Incident).where(Incident.status.in_(["open", "investigating", "contained"]))
                              .order_by(Incident.created_at.desc()).limit(5)).scalars().all()
            return _resp("Active incidents", f"{len(rows)} active incident(s).",
                         [f"{i.reference} [{i.severity}] {i.title} - {i.status}" for i in rows] or ["No active incidents."],
                         ["Open an incident and use 'Summarize' for a structured briefing."])
        if any(w in ql for w in ("denied", "deny", "decision", "why")):
            rows = db.execute(select(AccessDecision).where(AccessDecision.decision != "ALLOW")
                              .order_by(AccessDecision.evaluated_at.desc()).limit(5)).scalars().all()
            return _resp("Recent non-allow decisions", "Most recent decisions that did not grant full access.",
                         [f"{d.decision} - {d.user.email if d.user else '?'} -> {d.resource.name if d.resource else '?'}: "
                          f"{d.reasons[0] if d.reasons else ''}" for d in rows] or ["None."],
                         ["Use 'Explain' on a decision for a full trace walkthrough."])
        if any(w in ql for w in ("login", "sign", "brute", "password", "activity", "summary", "today")):
            return self.review_activity(db, 24)
        return _resp("How I can help",
                     "I am a local, rule-based assistant. I can answer questions about risk, incidents, access decisions and recent activity.",
                     ["Try: 'Who are the riskiest users?', 'Show active incidents', 'Why was access denied?', "
                      "'Summarize activity today'."], [])


def get_assistant() -> AssistantProvider:
    return LocalRuleAssistant()
